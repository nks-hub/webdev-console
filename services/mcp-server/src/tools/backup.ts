// Backup management — create, list, restore.
import { z } from 'zod'
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'

import { daemonClient } from '../daemonClient.js'
import type { RegisterOptions } from '../index.js'
import { IntentTokenSchema, intentHeaders } from './confirmation.js'
import { safe } from '../formatting.js'
import { ConfirmYesSchema, capabilityNote } from '../schemas.js'

// Restoring and deleting backups are the daemon's backup_restore capability.
const BACKUP_RESTORE = capabilityNote('Backup restore and delete')

export function registerBackupTools(server: McpServer, opts: RegisterOptions): void {
  server.registerTool(
    'wdc_list_backups',
    {
      title: 'List backups',
      description:
        'List all existing backup zip files under ~/.wdc/backups/, newest first.\n\n' +
        'Returns: { count, backups: [{ path, size (bytes), createdUtc, contentFlags }] }. contentFlags ' +
        'names what the archive holds (Vhosts, PluginConfigs, Ssl, Databases, Docroots).',
      inputSchema: {},
      annotations: {
        readOnlyHint: true,
        destructiveHint: false,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async () => safe(() => daemonClient.get('/api/backup/list')),
  )

  server.registerTool(
    'wdc_backup_stats',
    {
      title: 'Backup statistics',
      description: 'Count and total size of the backups, and when the newest one was made.\n\n' +
        'Returns: { count, totalSize (bytes), lastCreatedUtc }.',
      inputSchema: {},
      annotations: { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false },
    },
    async () => safe(() => daemonClient.get('/api/backup/stats')),
  )

  if (opts.readonly) return

  server.registerTool(
    'wdc_create_backup',
    {
      title: 'Create backup',
      description:
        'Create a zip backup in ~/.wdc/backups/ with the content chosen in WDC Settings → Backups: ' +
        'site configs, plugin configs and site certificates by default; a mysqldump of every user ' +
        'database and the site folders when the user turned those on. state.db is always included, ' +
        'binaries never.\n\n' +
        'Returns: { path, files, size (bytes), contentFlags, skipped: [{ content, detail }] }. ' +
        'contentFlags names what the archive really holds. skipped lists what was asked for but left ' +
        'out (for example MySQL not running, a site folder missing); tell the user about it.',
      inputSchema: {},
      annotations: {
        readOnlyHint: false,
        destructiveHint: false,
        idempotentHint: false,
        openWorldHint: false,
      },
    },
    async () => safe(() => daemonClient.post('/api/backup')),
  )

  // Backup zips live under ~/.wdc/backups/, file names generated by
  // BackupManager as wdc-backup-YYYY-MM-DD-HH-MM-SS.zip. Enforce the
  // `.zip` suffix + bounded length at the MCP edge so malformed paths
  // (traversal payloads, directory strings, megabyte inputs, NUL
  // bytes) never reach the daemon restore handler. Server-side still
  // validates, but reject at the cheapest point. Mirrors hardening in
  // ServiceIdSchema/PluginIdSchema/CloudflareIdSchema (commits fda3f9c,
  // 8332610, cf22160).
  const BackupPathSchema = z
    .string()
    .min(1)
    .max(4096)
    .refine((p) => p.toLowerCase().endsWith('.zip'), {
      message: 'Backup path must end in .zip',
    })
    .refine((p) => !p.includes('\0'), {
      message: 'Backup path must not contain NUL bytes',
    })
    .describe('Absolute path to a backup .zip under the backup root')

  server.registerTool(
    'wdc_restore_backup',
    {
      title: 'Restore backup (destructive)',
      description:
        'DESTRUCTIVE: Restore a backup zip file over the current state (site configs, certificates, ' +
        'plugin configs, state.db). Database dumps and site files in the archive are not restored. ' +
        'The daemon creates a safety pre-restore backup automatically.\n\n' +
        `${BACKUP_RESTORE} Each restore needs the user's approval: ` +
        'wdc_request_confirmation(operation: "backup_restore").\n\n' +
        'Args:\n  path: Absolute path to a backup zip under the backup root.\n  confirm: Must be "YES".\n' +
        '  intentToken: Approved intent.\n\n' +
        'You MUST show the user the backup path + timestamp before passing confirm="YES".\n\n' +
        'Returns: { restored, safetyBackup, archive }.',
      inputSchema: {
        path: BackupPathSchema,
        confirm: ConfirmYesSchema,
        intentToken: IntentTokenSchema,
      },
      annotations: {
        readOnlyHint: false,
        destructiveHint: true,
        idempotentHint: false,
        openWorldHint: false,
      },
    },
    async ({ path, intentToken }) =>
      safe(() => daemonClient.post('/api/restore', { path }, intentHeaders(intentToken))),
  )

  server.registerTool(
    'wdc_delete_backup',
    {
      title: 'Delete backup (destructive)',
      description:
        'DESTRUCTIVE: Delete a backup zip from the backup directory. It cannot be recovered.\n\n' +
        `${BACKUP_RESTORE} Each delete needs the user's approval: ` +
        'wdc_request_confirmation(operation: "backup_delete", target: the backup file name), then pass the ' +
        'approved intentToken.\n\n' +
        'Args:\n  name: File name of the backup (or its path from wdc_list_backups).\n  confirm: Must be "YES".\n' +
        '  intentToken: Approved intent.\n\n' +
        'You MUST show the user which backup (name and date) will be deleted before passing confirm="YES".\n\n' +
        'Returns: { deleted }.',
      inputSchema: {
        name: BackupPathSchema.describe('Backup file name like wdc-backup-2026-01-01-10-00-00.zip, or its path'),
        confirm: ConfirmYesSchema,
        intentToken: IntentTokenSchema,
      },
      annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: false, openWorldHint: false },
    },
    async ({ name, intentToken }) =>
      safe(() => daemonClient.delete(`/api/backup/${encodeURIComponent(backupFileName(name))}`, intentHeaders(intentToken))),
  )

  server.registerTool(
    'wdc_restore_backup_by_id',
    {
      title: 'Restore backup by name (destructive)',
      description:
        'DESTRUCTIVE: Restore a backup from the backup directory, by file name, over the current state ' +
        '(site configs, certificates, plugin configs, state.db). Database dumps and site files in the ' +
        'archive are not restored. The daemon makes a safety backup first.\n\n' +
        `${BACKUP_RESTORE} Each restore needs the user's approval: ` +
        'wdc_request_confirmation(operation: "backup_restore").\n\n' +
        'Args:\n  id: File name of the backup (or its path from wdc_list_backups).\n  confirm: Must be "YES".\n' +
        '  intentToken: Approved intent.\n\n' +
        'You MUST show the user the backup name and date before passing confirm="YES".\n\n' +
        'Returns: { restored, safetyBackup, archive }.',
      inputSchema: {
        id: BackupPathSchema.describe('Backup file name like wdc-backup-2026-01-01-10-00-00.zip, or its path'),
        confirm: ConfirmYesSchema,
        intentToken: IntentTokenSchema,
      },
      annotations: { readOnlyHint: false, destructiveHint: true, idempotentHint: false, openWorldHint: false },
    },
    async ({ id, intentToken }) =>
      safe(() =>
        daemonClient.post(`/api/backup/${encodeURIComponent(backupFileName(id))}/restore`, undefined, intentHeaders(intentToken)),
      ),
  )
}

/**
 * Backups live directly in the backup directory, and the daemon resolves
 * `{id}` against it, so only the file name is sent (a full path's slashes
 * would not survive the route segment).
 */
export function backupFileName(nameOrPath: string): string {
  const parts = nameOrPath.split(/[\\/]/)
  return parts[parts.length - 1]!
}
